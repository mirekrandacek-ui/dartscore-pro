export function pickNextAdThanks(lang, lastIndex = -1, random = Math.random) {
  const messages = AD_THANKS_MESSAGES[lang] || AD_THANKS_MESSAGES.en;
  const lastValid = Number.isInteger(lastIndex) && lastIndex >= 0 && lastIndex < messages.length;
  const slots = messages.length - (lastValid ? 1 : 0);
  const draw = Math.min(slots - 1, Math.max(0, Math.floor(random() * slots)));
  const index = lastValid && draw >= lastIndex ? draw + 1 : draw;
  return { index, message: messages[index] };
}
